  function parseExactFileScope(value) {
    const names = value.split(/[,\n\r]+/).map((name) => name.trim()).filter(Boolean);
    if (!names.length) throw new Error("Add the exact authorized filenames, separated by commas or new lines.");
    if (names.length > maxFileCount) throw new Error(`A review scope can name no more than ${maxFileCount} source files.`);
    const normalized = [];
    const seen = new Set();
    for (const filename of names) {
      if (filename !== filename.split(/[\\/]/).pop() || filename === "." || filename === ".." || /[*?:#@\s\u0000-\u001f]/.test(filename)) {
        throw new Error("For strict file-level authorization, enter simple exact filenames only—no paths, wildcards, URLs, spaces, or environment files.");
      }
      const extension = fileExtension(filename);
      if (!allowedExtensions.has(extension)) {
        throw new Error(`“${filename.slice(0, 80)}” is not an accepted source text filename.`);
      }
      const key = filename.toLocaleLowerCase("en-US");
      if (seen.has(key)) throw new Error("A filename is listed more than once. Remove duplicates from the approved scope.");
      seen.add(key);
      normalized.push(filename);
    }
    return normalized;
  }

