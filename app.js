  function validateUploadedFiles(fileList) {
    const files = [...fileList];
    if (files.length > maxFileCount) throw new Error(`Choose no more than ${maxFileCount} source files at a time.`);

    let total = 0;
    for (const file of files) {
      if (!allowedExtensions.has(fileExtension(file.name))) {
        throw new Error(`“${file.name.slice(0, 80)}” is not a supported text file. Archives, executables, hidden files, and binary files are not accepted.`);
      }
      if (file.size > maxFileBytes) throw new Error(`“${file.name.slice(0, 80)}” exceeds the 512 KB per-file limit.`);
      total += file.size;
    }
    if (total > maxTotalBytes) throw new Error("Selected files exceed the 2 MB total limit.");
    return files;
  }

