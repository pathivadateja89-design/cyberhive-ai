  byId("review-form").addEventListener("submit", async (event) => {
    event.preventDefault();
    const error = byId("review-error");
    const feedback = byId("review-progress");
    error.hidden = true;
    feedback.hidden = true;
    byId("run-result").hidden = true;

    const project = projectById(byId("review-project").value);
    const authorized = byId("authorization-check").checked;
    const scope = byId("review-scope").value.trim();
    if (!project || project.source !== "local" || !authorized || !project.authorizationAttested) {
      showReviewError("Select a locally registered project and explicitly attest its written authorization and exact scope before reviewing source.");
      return;
    }
    if (!scope || scope.length > 500) {
      showReviewError("Enter the precise, owner-authorized source scope before continuing.");
      return;
    }

    let input;
    let requestedFiles;
    try {
      requestedFiles = parseExactFileScope(scope);
      const approvedFiles = new Set(project.authorizedFiles || parseExactFileScope(project.scope));
      const outOfScope = requestedFiles.filter((filename) => !approvedFiles.has(filename));
      if (outOfScope.length) {
        throw new Error(`The source-review scope includes ${outOfScope.join(", ")}, which is not in this project's attested authorization scope.`);
      }
      input = selectedInputFiles();
      const providedFiles = input.metadata.map((file) => file.name);
      const missingFiles = requestedFiles.filter((name) => !providedFiles.includes(name));
      const extraFiles = providedFiles.filter((name) => !requestedFiles.includes(name));
      if (missingFiles.length) throw new Error(`Provide each approved filename before scanning: ${missingFiles.join(", ")}.`);
      if (extraFiles.length) throw new Error(`Remove files outside the explicitly selected scope: ${extraFiles.join(", ")}.`);
      window.CyberHiveEngine.validateFiles(input.metadata.map((file) => ({ name: file.name, content: " ".repeat(Math.min(file.size, 1)) })));
    } catch (validationError) {
      showReviewError(validationError instanceof Error ? validationError.message : "Choose supported text source files.");
      return;
    }

    state.reviewRunNumber += 1;
    const controller = new AbortController();
    state.reviewController = controller;
    const runNumber = state.reviewRunNumber;
    byId("progress-title").textContent = "Checking supplied files…";
    byId("progress-detail").textContent = `Reviewing ${input.metadata.length} supplied file${input.metadata.length === 1 ? "" : "s"} against local text-pattern checks.`;
    byId("progress-fill").style.width = "4%";
    byId("progress-caption").textContent = "Reading submitted file text…";
    setReviewBusy(true);

    try {
      feedback.textContent = "Authorization attested. Source is read as text in this browser tab and is not transmitted.";
      feedback.hidden = false;
      const sourceFiles = await readReviewFiles(controller.signal, input.pasted);
      if (controller.signal.aborted || runNumber !== state.reviewRunNumber) return;
      const result = await window.CyberHiveEngine.analyzeFiles(sourceFiles, {
        signal: controller.signal,
        onProgress(progress) {
          if (runNumber !== state.reviewRunNumber) return;
          const completedLines = progress.linesReviewed || 0;
          setProgress(completedLines, progress.totalLines || 1, progress.phase);
          byId("progress-caption").textContent = `${progress.phase} · ${completedLines.toLocaleString()} of ${(progress.totalLines || 1).toLocaleString()} lines reviewed`;
        }
      });
      if (controller.signal.aborted || runNumber !== state.reviewRunNumber) return;

      const createdAt = new Date();
      const runId = crypto.randomUUID();
      const prefix = `${runId}:`;
      const findings = result.findings.map((finding) => Object.freeze({
        ...finding,
        id: `${prefix}${finding.id}`,
        projectId: project.id,
        projectName: project.name,
        scope,
        assessmentId: runId,
        createdAt: createdAt.toISOString()
      }));
      const run = Object.freeze({
        id: runId,
        projectId: project.id,
        projectName: project.name,
        scope,
        createdAt: createdAt.toISOString(),
        label: "Just now",
        filesReviewed: result.filesReviewed,
        bytesReviewed: result.bytesReviewed,
        linesReviewed: result.linesReviewed,
        findingsCount: findings.length,
        findings: Object.freeze(findings)
      });

      state.findings = [...findings, ...state.findings];
      state.assessments.unshift(run);
      updateCounters();
      byId("progress-fill").style.width = "100%";
      byId("progress-caption").textContent = `${result.filesReviewed} supplied ${result.filesReviewed === 1 ? "file" : "files"} reviewed · no external connections made`;
      byId("progress-title").textContent = "Local source review complete.";
      byId("progress-detail").textContent = `${findings.length} potential pattern match${findings.length === 1 ? "" : "es"} · all require human verification.`;
      renderRunResult(run);
      byId("run-result").scrollIntoView({ block: "nearest", behavior: "smooth" });
    } catch (reviewError) {
      if (reviewError instanceof Error && reviewError.name === "AbortError") {
        feedback.textContent = "Review cancelled. The source was not sent or saved, and no results were generated.";
        feedback.hidden = false;
        byId("progress-caption").textContent = "Review cancelled before results were produced.";
      } else {
        showReviewError(reviewError instanceof Error ? reviewError.message : "The local review failed. Check the selected text files and try again.");
      }
    } finally {
      if (runNumber === state.reviewRunNumber) {
        state.reviewController = null;
        byId("authorization-check").checked = false;
        setReviewBusy(false);
        if (byId("progress-title").textContent === "Local source review complete.") {
          window.setTimeout(() => { byId("run-progress-card").hidden = true; }, 900);
        } else {
          window.setTimeout(() => { byId("run-progress-card").hidden = true; }, 700);
        }
      }
    }
  });

