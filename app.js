  function selectedInputFiles() {
    const pasted = byId("pasted-source").value;
    const fileEntries = state.reviewFiles;
    if (!pasted.trim() && fileEntries.length === 0) {
      throw new Error("Select at least one supported source file or paste authorized source text.");
    }

    const totalFiles = fileEntries.length + (pasted.trim() ? 1 : 0);
    if (totalFiles > maxFileCount) throw new Error(`Choose no more than ${maxFileCount} files, including pasted source.`);

    const seen = new Set();
    const metadata = fileEntries.map((file) => {
      if (file.size > maxFileBytes) throw new Error(`“${file.name.slice(0, 80)}” exceeds the 512 KB per-file review limit.`);
      const normalized = file.name.toLocaleLowerCase("en-US");
      if (seen.has(normalized)) throw new Error("Two selected files have the same filename. Select a unique, explicitly authorized filename instead.");
      seen.add(normalized);
      return { name: file.name, size: file.size };
    });

    if (pasted.trim()) {
      const language = byId("pasted-language").value;
      const filename = `pasted-source.${language}`;
      if (seen.has(filename.toLocaleLowerCase("en-US"))) throw new Error("Remove the uploaded file named pasted-source or rename it before also pasting text.");
      if (!allowedExtensions.has(fileExtension(filename))) throw new Error("Choose a supported language for pasted source.");
      seen.add(filename.toLocaleLowerCase("en-US"));
      metadata.push({ name: filename, size: new TextEncoder().encode(pasted).length });
    }

    const totalBytes = metadata.reduce((sum, file) => sum + file.size, 0);
    if (totalBytes > maxTotalBytes) throw new Error("Selected files and pasted source exceed the 2 MB total limit.");
    return { metadata, pasted };
  }

  async function readReviewFiles(signal, pastedText) {
    const source = [];
    if (pastedText.trim()) {
      source.push({ name: `pasted-source.${byId("pasted-language").value}`, content: pastedText });
    }
    for (const file of state.reviewFiles) {
      if (signal.aborted) throw new DOMException("Review cancelled.", "AbortError");
      if (typeof file.text !== "function") throw new Error(`The browser could not read “${file.name}” as text.`);
      source.push({ name: file.name, content: await file.text() });
    }
    if (signal.aborted) throw new DOMException("Review cancelled.", "AbortError");
    return source;
  }

