  function downloadReport(run) {
    const contents = buildReport(run);
    const downloadUrl = URL.createObjectURL(new Blob([contents], { type: "text/markdown;charset=utf-8" }));
    const link = element("a");
    link.href = downloadUrl;
    link.download = `cyberhive-local-review-${safeFilename(run.projectName)}.md`;
    link.click();
    window.setTimeout(() => URL.revokeObjectURL(downloadUrl), 1000);
  }

