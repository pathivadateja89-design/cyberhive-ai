  function visibleFindings() {
    const query = byId("finding-search").value.trim().toLowerCase();
    const severity = byId("severity-filter").value;
    return sortFindings(allFindings().filter((finding) => {
      if (state.activeFindingSource === "local" && finding.source !== "local") return false;
      if (state.activeFindingSource === "demo" && finding.source !== "demo") return false;
      if (severity !== "all" && finding.severity !== severity) return false;
      const value = `${finding.title} ${finding.projectName} ${finding.filename} ${finding.ruleId}`.toLowerCase();
      return value.includes(query);
    }));
  }

